const page = await readFile(path.join(root, "dist/concepts/measurement/validity/index.html"), "utf8");
const required = ["妥当性", "まず何を問う概念なのか", "[1]", "PHQ-9", "GitHub stars", "参考文献", "Status: DRAFT"];
